"""Hexagon bundles indexed by graphs.  Vertices c = base factors P^{b_c}; edges i = hexagons (dP_6):
hexagon i joins plus_i and minus_i and is twisted by +r_i along the ray f^c_0 of P^{b_c}, c = plus_i,
and by -r_i along f^c_0, c = minus_i (the orientation is immaterial: -1 on the hexagon reverses it).
X(G) is the (dP_6)^j-bundle over prod_c P^{b_c};  n = 2j + sum b_c,  rho - n = 2j + k - sum b_c.

Fano: the primitive relations are those of the hexagons and f^c_0+...+f^c_{b_c} = (sum of the
twists at c), of degree b_c + 1 - deg(c); so X(G) is Fano iff deg(c) <= b_c for every c.
The ray matroid is connected iff G is connected.  For a tree with b_c = deg(c) ("saturated"):
n = 4j and rho - n = j + 1.  The star with j edges is X_j(j) of xjb_family.py; paths use only
P^1 and P^2.

Degrees.  With a_i = <m_i, r_i>, s_c = sum_{plus_i=c} a_i - sum_{minus_i=c} a_i, L_c = b_c+1+s_c,
the slice of the moment polytope over (m_i) is a product of simplices of sizes L_c:
    D = n! int prod_c L_c^{b_c}/b_c!,      d(f^c_t) = (n-1)! int (b_c/L_c) prod ...,
    d(h in hexagon i) = (n-1)! int prod ... with the a_i-measure replaced by that of the edge of h,
all against prod (2-|a_i|) da_i.  Evaluated exactly by polynomial expansion.

Stability: symmetry reduction (notes/theory.md Prop. 2.5) with the group generated by the hexagon
reflections fixing r_i, the permutations of f^c_1..f^c_{b_c}, and the graph automorphisms; the
invariant ray-spanned subspaces are enumerated as closed unions of ray orbits.
Usage: tree_family.py            (validation against xjb_family + the table of trees)"""
