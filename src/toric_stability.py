def fmt_frac(pair):
    num, den = pair
    return str(num) if den == 1 else f"{num}/{den}"


def report(res):
    bary = "(" + ", ".join(fmt_frac(b) for b in res["barycenter"]) + ")"
    line = (f"{res['name']:<34} dim {res['dim']}  "
            f"(-K)^n = {res['anticanonical_degree']:>3}   "
            f"mu(T) = {fmt_frac(res['mu_TX']):>6}   "
            f"max mu(V) = {fmt_frac(res['max_subsheaf_slope']):>6}   "
            f"{res['verdict']:<20} "
            f"KE: {'yes' if res['kahler_einstein'] else 'no '}  bary = {bary}")
    print(line)


def main():
    results = []
    print("Tangent-bundle stability w.r.t. -K  (Klyachko slope check, exact)")
    print("=" * 130)
    for name, rays in VALIDATION.items():
        res = analyze([tuple(v) for v in rays], name)
        report(res)
        results.append(res)
    out = os.path.join(os.path.dirname(__file__), "..", "output",
                       "validation_verdicts.json")
    with open(out, "w") as f:
        json.dump(results, f, indent=1)
    print(f"\nwrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
